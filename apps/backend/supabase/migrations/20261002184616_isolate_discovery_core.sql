create function public.discovery_update_job_search_vector()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.job_search_vector :=
    setweight(to_tsvector('english', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(new."companyName", '')), 'B');
  return new;
end;
$$;

create trigger discovery_jobs_search_vector
before insert or update of title, "companyName" on public.discovery_jobs
for each row execute function public.discovery_update_job_search_vector();

create function public.discovery_list_jobs(
  jobs_status public.discovery_job_status,
  jobs_after text,
  jobs_page_size integer,
  jobs_search text default null,
  jobs_site_ids integer[] default null,
  jobs_link_ids integer[] default null,
  jobs_labels text[] default null
)
returns setof public.discovery_jobs
language sql
security invoker
set search_path = ''
as $$
  select j.*
  from public.discovery_jobs j
  where j.user_id = (select auth.uid())
    and j.status = jobs_status
    and (
      jobs_after is null
      or (j.updated_at, j.id) < (
        split_part(jobs_after, '!', 2)::timestamp,
        split_part(jobs_after, '!', 1)::bigint
      )
    )
    and (cardinality(jobs_site_ids) = 0 or jobs_site_ids is null or j."siteId" = any(jobs_site_ids))
    and (cardinality(jobs_link_ids) = 0 or jobs_link_ids is null or j.link_id = any(jobs_link_ids))
    and (cardinality(jobs_labels) = 0 or jobs_labels is null or j.labels && jobs_labels)
    and (jobs_search is null or j.job_search_vector @@ plainto_tsquery('english', jobs_search))
  order by j.updated_at desc, j.id desc
  limit jobs_page_size;
$$;

create function public.discovery_count_jobs(
  jobs_status public.discovery_job_status default null,
  jobs_search text default null,
  jobs_site_ids integer[] default null,
  jobs_link_ids integer[] default null,
  jobs_labels text[] default null
)
returns table(status public.discovery_job_status, job_count bigint)
language sql
security invoker
set search_path = ''
as $$
  select j.status, count(*)
  from public.discovery_jobs j
  where j.user_id = (select auth.uid())
    and (jobs_status is null or j.status = jobs_status)
    and (cardinality(jobs_site_ids) = 0 or jobs_site_ids is null or j."siteId" = any(jobs_site_ids))
    and (cardinality(jobs_link_ids) = 0 or jobs_link_ids is null or j.link_id = any(jobs_link_ids))
    and (cardinality(jobs_labels) = 0 or jobs_labels is null or j.labels && jobs_labels)
    and (jobs_search is null or j.job_search_vector @@ plainto_tsquery('english', jobs_search))
  group by j.status
  order by j.status;
$$;

create function public.discovery_count_chatgpt_usage(
  for_user_id uuid,
  cost_increment numeric,
  input_tokens_increment integer,
  output_tokens_increment integer
)
returns void
language sql
security invoker
set search_path = ''
as $$
  update public.discovery_advanced_matching
  set ai_api_cost = ai_api_cost + cost_increment,
      ai_api_input_tokens_used = ai_api_input_tokens_used + input_tokens_increment,
      ai_api_output_tokens_used = ai_api_output_tokens_used + output_tokens_increment
  where user_id = for_user_id and for_user_id = (select auth.uid());
$$;

create function public.discovery_log_ai_usage(
  for_user_id uuid,
  cost_increment numeric,
  input_tokens_increment bigint,
  output_tokens_increment bigint
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if for_user_id <> (select auth.uid()) then
    raise exception 'Not authorized';
  end if;

  insert into public.discovery_ai_usage_daily (user_id, usage_date, cost, input_tokens, output_tokens)
  values (for_user_id, current_date, cost_increment, input_tokens_increment, output_tokens_increment)
  on conflict (user_id, usage_date)
  do update set
    cost = public.discovery_ai_usage_daily.cost + excluded.cost,
    input_tokens = public.discovery_ai_usage_daily.input_tokens + excluded.input_tokens,
    output_tokens = public.discovery_ai_usage_daily.output_tokens + excluded.output_tokens,
    updated_at = now();
end;
$$;

