create type public.discovery_job_status as enum (
  'new',
  'applied',
  'archived',
  'processing',
  'excluded_by_advanced_matching'
);

create table public.discovery_sites (
  id bigint generated by default as identity primary key,
  name text not null,
  urls text[] not null,
  created_at timestamp with time zone not null default now(),
  "queryParamsToRemove" text[] null,
  logo_url text not null,
  blacklisted_paths text[] not null default '{/}'::text[],
  provider text not null unique,
  deprecated boolean not null default false,
  incognito_support boolean not null default false
);

create table public.discovery_links (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  url text not null,
  title text not null,
  site_id bigint not null references public.discovery_sites (id) on update restrict on delete restrict,
  scrape_failure_count integer not null default 0,
  last_scraped_at timestamp with time zone not null default (now() at time zone 'utc'),
  scrape_failure_email_sent boolean not null default false
);

create table public.discovery_jobs (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  "externalId" text not null,
  "externalUrl" text not null,
  "siteId" bigint not null references public.discovery_sites (id) on update restrict on delete restrict,
  title text not null,
  "companyName" text not null,
  "companyLogo" text null,
  location text null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  salary text null,
  tags text[] not null default '{}'::text[],
  "jobType" text null,
  status public.discovery_job_status not null default 'new',
  description text null,
  labels text[] not null default '{}'::text[],
  link_id bigint null references public.discovery_links (id) on update cascade on delete set null,
  exclude_reason text null,
  job_search_vector tsvector,
  constraint discovery_jobs_user_external_id_key unique (user_id, "externalId")
);

create index discovery_jobs_user_updated_status_idx
  on public.discovery_jobs (user_id, updated_at desc, id desc, status);

