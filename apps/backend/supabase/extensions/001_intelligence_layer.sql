-- Purpose:
-- Add the first set of additive tables for the new intelligence layer
-- without modifying the inherited discovery pipeline too aggressively.

create table if not exists public.user_search_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  target_titles text[] not null default '{}'::text[],
  target_skills text[] not null default '{}'::text[],
  excluded_skills text[] not null default '{}'::text[],
  salary_min integer null,
  preferred_locations text[] not null default '{}'::text[],
  remote_preferences text[] not null default '{}'::text[],
  seniority_preferences text[] not null default '{}'::text[],
  work_authorization text null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint user_search_profiles_user_id_key unique (user_id)
);

alter table public.user_search_profiles enable row level security;

create policy "enable all for users based on user_id on user_search_profiles"
on public.user_search_profiles
as permissive
for all
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

