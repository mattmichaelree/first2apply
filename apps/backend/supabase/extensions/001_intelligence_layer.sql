create table if not exists public.job_enrichments (
  id bigint generated by default as identity primary key,
  job_id bigint not null references public.jobs (id) on delete cascade,
  normalized_title text null,
  normalized_company text null,
  normalized_location text null,
  remote_type text null,
  seniority_level text null,
  salary_normalized_min integer null,
  salary_normalized_max integer null,
  employment_type text null,
  required_skills text[] not null default '{}'::text[],
  excluded_geographies text[] not null default '{}'::text[],
  enrichment_version text not null default 'v1',
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint job_enrichments_job_id_key unique (job_id)
);

alter table public.job_enrichments enable row level security;

create policy "enable select for user-owned job enrichments"
on public.job_enrichments
as permissive
for select
to authenticated
using (
  exists (
    select 1
    from public.jobs
    where public.jobs.id = job_enrichments.job_id
      and public.jobs.user_id = auth.uid()
  )
);

